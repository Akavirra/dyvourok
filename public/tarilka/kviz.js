const $ = id => document.getElementById(id);
let i = 0, score = 0, res = [], order = [];
const shuffle = a => { for (let k = a.length - 1; k > 0; k--) { const j = Math.random() * (k + 1) | 0; [a[k], a[j]] = [a[j], a[k]]; } return a; };

function dots() {
  $('dots').innerHTML = Q.map((_, k) => `<i class="${res[k] === true ? 'ok' : res[k] === false ? 'no' : k === i ? 'now' : ''}"></i>`).join('');
}
function start() { i = 0; score = 0; res = []; show(); }
function show() {
  const x = Q[i];
  order = shuffle(x.o.map((_, k) => k));
  dots();
  $('body').innerHTML = `<div class="q"><div class="num">Питання ${i + 1} з ${Q.length}</div><h2>${x.q}</h2>
    ${x.pic.length ? `<div class="pic">${x.pic.map(p => `<img src="img/${p}.webp" alt="">`).join('')}</div>` : ''}
    <div class="opts" id="opts">${order.map((k, n) => `<button class="opt" data-k="${k}"><span class="l">${L[n]}</span>${x.o[k]}</button>`).join('')}</div>
    <div id="why"></div><div class="qnav"><button class="btn" id="nx" hidden>${i < Q.length - 1 ? 'Далі →' : 'Результат'}</button></div></div>`;
  $('opts').onclick = e => { const b = e.target.closest('.opt'); if (b) answer(+b.dataset.k, b); };
  $('nx').onclick = () => { i++; i < Q.length ? show() : end(); };
}
function answer(k, b) {
  const x = Q[i], ok = k === x.a;
  res[i] = ok; if (ok) score++;
  $('opts').classList.add('done');
  $('opts').querySelectorAll('.opt').forEach(o => {
    const kk = +o.dataset.k;
    o.classList.add(kk === x.a ? 'ok' : o === b ? 'no' : 'dim');
  });
  $('why').innerHTML = `<div class="why ${ok ? 'ok' : 'no'}"><b>${ok ? 'Так!' : 'Не зовсім.'}</b> ${x.w}</div>`;
  $('nx').hidden = false; $('nx').focus({preventScroll: true});
  dots();
}
function end() {
  i = Q.length; dots();
  const msg = score >= Math.ceil(Q.length * .9) ? 'Ти чудово знаєш тарілку!' : score >= Math.ceil(Q.length * .6) ? `Чудово! Ще трохи — і всі ${Q.length}.` : 'Добрий початок! Спробуй ще раз — тепер ти знаєш більше.';
  $('body').innerHTML = `<div class="end"><div class="big">${score} / ${Q.length}</div><p>${msg}</p>
    <div class="row"><button class="btn" id="again">Пройти ще раз</button><a class="btn sun" href="gra.html">Гра «Збери тарілку»</a></div></div>`;
  $('again').onclick = start;
}
